"""
Writes the rows of the paper's data tables to paper/tables/*.tex and every
number quoted in the text to paper/tables/numbers.tex (as LaTeX macros), from
the JSON files in results/. Nothing in the paper is typed in by hand.

    python3 paper_eval/make_tables.py
"""

import os
import statistics

from common import read, PAPER, reduction

TABLES = os.path.join(PAPER, "tables")
HEADER = "% generated by paper_eval/make_tables.py -- do not edit by hand\n"

macros = {}


def macro(name, value, fmt="{:,}"):
    assert name.isalpha(), name
    text = fmt.format(value) if not isinstance(value, str) else value
    macros[name] = text.replace(",", "{,}") if fmt == "{:,}" else text


def pct(v):
    """One decimal; negative values get a typeset minus sign."""
    text = f"{abs(v):.1f}"
    return f"$-${text}" if v < 0 and text != "0.0" else text


def write(name, rows):
    with open(os.path.join(TABLES, name), "w", encoding="utf-8") as f:
        f.write(HEADER)
        for r in rows:
            f.write(" & ".join(str(x) for x in r) + " \\\\\n")


def rng(values, fmt=pct):
    return fmt(min(values)), fmt(max(values))


LAYOUT_TEMPLATE = r"""%% Fig: byte layout of the three encodings of benchmark S2, drawn to scale.
%% generated by paper_eval/make_tables.py from results/measure.json -- do not edit by hand
\documentclass[border=2pt]{standalone}
\usepackage{mathptmx}
\usepackage{tikz}
\begin{document}
\begin{tikzpicture}[font=\tiny, x=0.38mm, y=1mm]
  %% helper: \fld{x0}{width}{row y}{fill}{label}
  \newcommand{\fld}[5]{\draw[fill=#4, draw=black!70] (#1,#3) rectangle ++(#2,-6);
    \node[align=center] at ({#1+#2/2},{#3-3}) {#5};}
%(body)s
\end{tikzpicture}
\end{document}
"""


def write_layout_figure(r):
    lay = r["layout"]
    lines = []

    def row(title, y, fields, note):
        lines.append(f"  \\node[anchor=west, font=\\scriptsize\\bfseries] at (0,{y + 3}) {{{title}}};")
        x = 0
        for width, fill, label in fields:
            lines.append(f"  \\fld{{{x}}}{{{width}}}{{{y}}}{{{fill}}}{{{label}}}")
            x += width
        lines.append(f"  \\node[align=left, anchor=north west] at (0,{y - 7}) {{{note}}};")

    c = lay["clir"]
    row(f"(a) CLIR package, {c['total']} B", 6,
        [(c["header"], "black!25", ""), (c["pool"], "black!12", f"pool\\\\{c['pool']}"),
         (c["structure"], "black!8", ""), (c["instructions"], "white", f"instructions {c['instructions']}")],
        f"magic \\texttt{{CLIR}} + version {c['header']} B; pool of {c['pool_entries']} literals; "
        f"function, block and per-block instruction counts {c['structure']} B")
    h = lay["huffman"]
    mode = {0: "sparse list", 1: "bitmap", 2: "dense table"}[h["table_mode"]]
    row(f"(b) CLIR + canonical Huffman, {h['total']} B", -17,
        [(h["length"] + h["mode"], "black!25", ""),
         (h["table"], "black!35", f"code lengths\\\\{h['table']}"), (h["payload"], "white", f"payload {h['payload']}")],
        f"input length (LEB128) and mode byte {h['length'] + h['mode']} B; {h['symbols']} code lengths as a {mode}")
    k = lay["columnar"]
    flag = "1: Huffman-coded" if k["coded"] else "0: stored without entropy coding"
    row(f"(c) Columnar container, {k['total']} B (flag {flag})", -36,
        [(k["flag"] + k["magic"] + k["functions"] + k["prefixes"], "black!25", ""),
         (k["opcodes"], "black!12", f"opcodes\\\\{k['opcodes']}"), (k["flags"], "black!8", f"flags\\\\{k['flags']}"),
         (k["deltas"], "black!16", f"$\\Delta$\\\\{k['deltas']}"),
         (k["immediates"], "white", f"immediates (literals, labels, $\\phi$ preds) {k['immediates']}"),
         (k["names"], "black!12", f"names\\\\{k['names']}")],
        f"flag, magic and counts {k['flag'] + k['magic'] + k['functions']} B; stream length prefixes {k['prefixes']} B")
    with open(os.path.join(PAPER, "figures", "fig_layout.tex"), "w", encoding="utf-8") as f:
        f.write(LAYOUT_TEMPLATE % {"body": "\n".join(lines)})


def main():
    os.makedirs(TABLES, exist_ok=True)
    m = read("measure.json")["benchmarks"]
    S = [r for r in m if r["set"] == "S"]
    K = [r for r in m if r["set"] == "K"]

    # ---- Table: benchmarks
    write("tab_bench_rows.tex", [
        (r["id"], r["focus"], r["source_bytes"], r["functions"], r["inputs"], r["tac_instructions"],
         r["blocks"], r["edges"], r["phis"]) for r in m])

    for tag, rows in (("S", S), ("K", K)):
        macro(f"src{tag}Min", min(r["source_bytes"] for r in rows))
        macro(f"src{tag}Max", max(r["source_bytes"] for r in rows))
    macro("inputsKMin", min(r["inputs"] for r in K))
    macro("inputsKMax", max(r["inputs"] for r in K))
    macro("benchCount", len(m))

    # ---- Table: optimization
    write("tab_opt_rows.tex", [
        (r["id"], r["tac_instructions"], r["opt_instructions_base_passes"], r["opt_instructions"],
         pct(r["instruction_reduction"]), r["opt_blocks"], r["passes"]["constant_folds"],
         r["passes"]["sccp_constants"], r["passes"]["copies_propagated"],
         r["passes"]["dead_instructions_removed"], r["passes"]["dead_blocks_removed"],
         r["passes"]["gvn_eliminations"]) for r in m])

    for tag, rows in (("S", S), ("K", K)):
        lo, hi = rng([r["instruction_reduction"] for r in rows])
        macro(f"red{tag}Min", lo, "{}")
        macro(f"red{tag}Max", hi, "{}")
        lo, hi = rng([r["instruction_reduction_base_passes"] for r in rows])
        macro(f"redBase{tag}Min", lo, "{}")
        macro(f"redBase{tag}Max", hi, "{}")
        macro(f"redMean{tag}", pct(statistics.mean(r["instruction_reduction"] for r in rows)), "{}")
        lo, hi = rng([r["clir_vs_raw_text"] for r in rows])
        macro(f"clirRaw{tag}Min", lo, "{}")
        macro(f"clirRaw{tag}Max", hi, "{}")
        lo, hi = rng([r["clir_vs_opt_text"] for r in rows])
        macro(f"clirOpt{tag}Min", lo, "{}")
        macro(f"clirOpt{tag}Max", hi, "{}")
    s5 = next(r for r in m if r["id"] == "S5")
    macro("sFiveBase", s5["opt_instructions_base_passes"])
    macro("sFiveAll", s5["opt_instructions"])
    macro("sFiveRaw", s5["tac_instructions"])
    macro("sFiveRawText", s5["raw_text_bytes"])
    macro("sFiveOptText", s5["opt_text_bytes"])
    macro("sFiveSsaText", s5["ssa_text_bytes"])
    macro("sFivePhiLines", s5["opt_text_growth"]["phi_lines"])
    macro("sFivePhiBytes", s5["opt_text_growth"]["phi_line_bytes"])
    macro("sFiveSuffixBytes", s5["opt_text_growth"]["version_suffix_bytes"])
    macro("vnHitsBench", sum(r["passes"]["gvn_eliminations"] for r in m))
    grown = [r["id"] for r in m if r["opt_text_bytes"] > r["raw_text_bytes"]]
    macro("textGrownCount", len(grown))
    lo, hi = rng([100 * (r["ssa_text_bytes"] - r["raw_text_bytes"]) / r["raw_text_bytes"] for r in m])
    macro("ssaTextGrowMin", lo, "{}")
    macro("ssaTextGrowMax", hi, "{}")
    lo, hi = rng([100 * (r["ssa_instructions"] - r["tac_instructions"]) / r["tac_instructions"] for r in m])
    macro("ssaInstrGrowMin", lo, "{}")
    macro("ssaInstrGrowMax", hi, "{}")
    macro("kRawText", sum(r["raw_text_bytes"] for r in K))
    macro("kOptText", sum(r["opt_text_bytes"] for r in K))
    macro("kPhiBytes", sum(r["opt_text_growth"]["phi_line_bytes"] for r in K))
    macro("kSuffixBytes", sum(r["opt_text_growth"]["version_suffix_bytes"] for r in K))
    macro("kRemovedInstr", sum(r["tac_instructions"] - r["opt_instructions"] for r in K))
    macro("textGrownIds", ", ".join(grown), "{}")
    s4 = next(r for r in m if r["id"] == "S4")
    macro("sFourClir", s4["clir_bytes"])
    macro("sFourPool", s4["clir_pool_bytes"])

    # ---- Table: sizes
    def huff(r):
        return f'{r["huffman_bytes"]} ({r["huffman_header_bytes"]}/{r["huffman_payload_bytes"]})'
    write("tab_size_rows.tex", [
        (r["id"], r["raw_text_bytes"], r["opt_text_bytes"],
         f'{r["clir_bytes"]} ({r["clir_pool_bytes"]}/{r["clir_body_bytes"]})',
         pct(r["clir_vs_raw_text"]), pct(r["clir_vs_opt_text"]), huff(r), r["freq_huffman_bytes"],
         f'{r["entropy_bound_bytes"]:.0f}', r["columnar_bytes"]) for r in m])
    helped = [r["id"] for r in m if r["huffman_bytes"] < r["clir_bytes"]]
    macro("huffHelpedBench", len(helped))
    macro("huffHelpedKernels", sum(1 for r in K if r["huffman_bytes"] < r["clir_bytes"]))
    lo, hi = rng([reduction(r["clir_bytes"], r["huffman_bytes"]) for r in K])
    macro("huffGainKMin", lo, "{}")
    macro("huffGainKMax", hi, "{}")
    lo, hi = rng([r["freq_huffman_bytes"] / r["clir_bytes"] for r in m], lambda v: f"{v:.1f}")
    macro("freqGrowMin", lo, "{}")
    macro("freqGrowMax", hi, "{}")
    lo, hi = rng([100 * r["huffman_header_bytes"] / r["huffman_bytes"] for r in m])
    macro("huffHeaderShareMin", lo, "{}")
    macro("huffHeaderShareMax", hi, "{}")
    macro("columnarLargerCount", sum(1 for r in m if r["columnar_bytes"] > r["clir_bytes"]))
    for tag, rows in (("S", S), ("K", K)):
        lo, hi = rng([r["density"]["raw_text_bits_per_raw_instr"] for r in rows])
        macro(f"densRaw{tag}Min", lo, "{}")
        macro(f"densRaw{tag}Max", hi, "{}")
        lo, hi = rng([r["density"]["clir_body_bits_per_opt_instr"] for r in rows])
        macro(f"densBody{tag}Min", lo, "{}")
        macro(f"densBody{tag}Max", hi, "{}")
        lo, hi = rng([r["density"]["clir_bits_per_raw_instr"] for r in rows])
        macro(f"densPkg{tag}Min", lo, "{}")
        macro(f"densPkg{tag}Max", hi, "{}")

    # ---- Table: comparison with compressors (optimized text)
    cmp = read("compare.json")
    rows = []
    for b in cmp["benchmarks"]:
        o = b["opt_text"]
        s = b["summary"]["opt_text"]
        rows.append((b["id"], o["input"], o["framed"]["brotli"], o["framed"]["zstd"], o["framed"]["xz"],
                     s["best_headerless"], s["best_dictionary"], b["clir"]["input"],
                     pct(s["clir_vs_best_framed"]), pct(s["clir_vs_best_headerless"]),
                     pct(s["clir_vs_best_dictionary"])))
    write("tab_compare_rows.tex", rows)
    for tag in ("S", "K"):
        bs = [b for b in cmp["benchmarks"] if b["set"] == tag]
        for key, name in (("clir_vs_best_framed", "Framed"), ("clir_vs_best_headerless", "Hdrless"),
                          ("clir_vs_best_dictionary", "Dict")):
            lo, hi = rng([b["summary"]["opt_text"][key] for b in bs])
            macro(f"cmp{name}{tag}Min", lo, "{}")
            macro(f"cmp{name}{tag}Max", hi, "{}")
            macro(f"cmp{name}{tag}Wins", sum(1 for b in bs if b["summary"]["opt_text"][key] > 0))
        lo, hi = rng([b["summary"]["raw_text"]["clir_vs_best_framed"] for b in bs])
        macro(f"cmpRawText{tag}Min", lo, "{}")
        macro(f"cmpRawText{tag}Max", hi, "{}")
    dict_losers = [b["id"] for b in cmp["benchmarks"] if b["summary"]["opt_text"]["clir_vs_best_dictionary"] < 0]
    macro("dictLosers", ", ".join(dict_losers), "{}")
    macro("dictLosersCount", len(dict_losers))
    hdr_losers = [b["id"] for b in cmp["benchmarks"] if b["summary"]["opt_text"]["clir_vs_best_headerless"] < 0]
    macro("hdrLosers", ", ".join(hdr_losers) if hdr_losers else "none", "{}")
    macro("dictBytes", cmp["settings"]["dictionary_bytes"])
    macro("dictTraining", cmp["settings"]["training_programs"])
    sc = cmp["scaling"]
    macro("scaleCmpWins", sum(1 for e in sc if e["clir"] < e["opt_text_best_framed"]))
    macro("scaleCmpCount", len(sc))
    lo, hi = rng([reduction(e["opt_text_best_framed"], e["clir"]) for e in sc])
    macro("scaleCmpMin", lo, "{}")
    macro("scaleCmpMax", hi, "{}")
    macro("scaleClirBrotliWins", sum(1 for e in sc if e["clir_brotli"] < e["opt_text_best_framed"]))
    lo, hi = rng([reduction(e["clir"], e["clir_brotli"]) for e in sc])
    macro("scaleBrotliGainMin", lo, "{}")
    macro("scaleBrotliGainMax", hi, "{}")
    v = cmp["versions"]
    macro("verPython", v["python"], "{}")
    macro("verBrotli", v["brotli"], "{}")
    macro("verZstd", v["zstandard"], "{}")
    macro("verZlib", v["zlib"], "{}")
    macro("verPlatform", v["platform"].replace("_", "\\_"), "{}")
    macro("verMachine", v["machine"].replace("_", "\\_"), "{}")

    # ---- Table: existing bytecode formats
    bl = read("baselines.json")
    write("tab_baselines_rows.tex", [
        (r["id"], r["clir"], r["java_class"], r["java_class_deflate"], r["bitcode_Oz"],
         r["bitcode_Oz_deflate"], f'{r["java_class"] / r["clir"]:.1f}', f'{r["bitcode_Oz"] / r["clir"]:.1f}')
        for r in bl["kernels"]])
    e = bl["empty_program"]
    write("tab_baselines_empty.tex", [("Empty", e["clir"], e["java_class"], "--", e["bitcode_Oz"], "--", "--", "--")])
    macro("emptyClir", e["clir"])
    macro("emptyJava", e["java_class"])
    macro("emptyBitcode", e["bitcode_Oz"])
    lo, hi = rng([r["java_class"] / r["clir"] for r in bl["kernels"]], lambda x: f"{x:.1f}")
    macro("javaRatioMin", lo, "{}")
    macro("javaRatioMax", hi, "{}")
    lo, hi = rng([(r["java_class"] - e["java_class"]) / (r["clir"] - e["clir"]) for r in bl["kernels"]],
                 lambda x: f"{x:.1f}")
    macro("javaNetRatioMin", lo, "{}")
    macro("javaNetRatioMax", hi, "{}")
    lo, hi = rng([r["bitcode_Oz"] / r["clir"] for r in bl["kernels"]], lambda x: f"{x:.0f}")
    macro("bitcodeRatioMin", lo, "{}")
    macro("bitcodeRatioMax", hi, "{}")
    lo, hi = rng([(r["bitcode_Oz"] - e["bitcode_Oz"]) / (r["clir"] - e["clir"]) for r in bl["kernels"]],
                 lambda x: f"{x:.0f}")
    macro("bitcodeNetRatioMin", lo, "{}")
    macro("bitcodeNetRatioMax", hi, "{}")
    macro("nativeMatches", sum(1 for r in bl["kernels"] if r["c_lite_matches_native"] and r["java_matches_native"]))
    macro("verClang", bl["tools"]["clang"], "{}")
    macro("verJavac", bl["tools"]["javac"], "{}")

    # ---- Table: time
    write("tab_time_rows.tex", [
        (r["id"],) + tuple(f'{r["time_ms"][k]:.2f}' for k in
                           ("front", "tac", "cfg_dom", "ssa", "opt", "clir_huffman", "columnar", "total"))
        for r in m])
    lo, hi = rng([r["time_ms"]["total"] for r in m], lambda x: f"{x:.2f}")
    macro("timeMin", lo, "{}")
    macro("timeMax", hi, "{}")
    lo, hi = rng([100 * r["time_ms"]["opt"] / r["time_ms"]["total"] for r in m])
    macro("optShareMin", lo, "{}")
    macro("optShareMax", hi, "{}")
    macro("timingRuns", read("measure.json")["timing_runs"])
    stages = ("front", "tac", "cfg_dom", "ssa", "opt", "clir_huffman", "columnar")
    macro("optLargestCount", sum(1 for r in m if max(stages, key=lambda k: r["time_ms"][k]) == "opt"))

    # ---- Differential testing
    d = read("difftest.json")
    v = d["variants"]
    write("tab_diff_rows.tex", [
        ("As released: five passes, floor \\texttt{/} and \\texttt{\\%}", "no",
         f'{v["released"]["programs"]:,}', f'{v["released"]["agree"]:,}',
         v["released"]["differ_division"], v["released"]["differ_other"]),
        ("Five passes, truncating \\texttt{/} and \\texttt{\\%}", "no",
         f'{v["corrected"]["programs"]:,}', f'{v["corrected"]["agree"]:,}',
         v["corrected"]["differ_division"], v["corrected"]["differ_other"]),
        ("All seven passes", "no", f'{v["all"]["programs"]:,}', f'{v["all"]["agree"]:,}',
         v["all"]["differ_division"], v["all"]["differ_other"]),
        ("All seven passes", "yes", f'{d["with_input"]["all"]["programs"]:,}',
         f'{d["with_input"]["all"]["agree"]:,}', d["with_input"]["all"]["differ_division"],
         d["with_input"]["all"]["differ_other"]),
    ])
    macro("diffPrograms", d["programs"])
    macro("diffInputPrograms", d["input_programs"])
    macro("diffReleasedDiffer", v["released"]["programs"] - v["released"]["agree"])
    macro("diffReleasedAgree", pct(v["released"]["agreement_percent"]), "{}")
    macro("diffReleasedRate", pct(100 - v["released"]["agreement_percent"]), "{}")
    macro("diffMinInstr", d["raw_instructions"]["min"])
    macro("diffMaxInstr", d["raw_instructions"]["max"])
    macro("diffTotalInstr", d["raw_instructions"]["total"])
    macro("diffInputTotalInstr", d["input_raw_instructions"]["total"])

    # ---- Ablation
    a = read("ablation.json")
    for tag, key in (("", "no_input"), ("In", "with_input")):
        x = a[key]
        ins = x["instructions"]
        macro(f"abl{tag}Programs", x["programs"])
        macro(f"abl{tag}Raw", x["raw_instructions"])
        macro(f"abl{tag}All", ins["all"])
        macro(f"abl{tag}Base", ins["base"])
        macro(f"abl{tag}None", ins["none"])
        macro(f"abl{tag}RedAll", pct(reduction(x["raw_instructions"], ins["all"])), "{}")
        macro(f"abl{tag}RedBase", pct(reduction(x["raw_instructions"], ins["base"])), "{}")
        macro(f"abl{tag}SsaGrowth", pct(100 * (ins["none"] - x["raw_instructions"]) / x["raw_instructions"]), "{}")
        macro(f"abl{tag}Phis", x["ssa_phis"])
        macro(f"abl{tag}BaseCopy", ins["base+copy_prop"])
        macro(f"abl{tag}BaseSccp", ins["base+sccp"])
        for p in ("fold", "sccp", "copy_prop", "gvn", "dce", "cfg", "trivial_phi"):
            name = "".join(w.capitalize() for w in p.split("_"))
            macro(f"abl{tag}No{name}", pct(100 * (ins[f"no_{p}"] - ins["all"]) / ins["all"]), "{}")
        macro(f"abl{tag}VnBase", x["stats"]["base"]["gvn_eliminations"])
        macro(f"abl{tag}VnBaseGain", ins["no_gvn"] - ins["all"])
        macro(f"abl{tag}VnPrograms", x["programs_with_vn_hits"]["all"])
        macro(f"abl{tag}VnAll", x["stats"]["all"]["gvn_eliminations"])
        macro(f"abl{tag}Copies", x["stats"]["all"]["copies_propagated"])

    # ---- Scaling
    s = read("scaling.json")
    progs = s["programs"]
    be = s["break_even_canonical"]
    bf = s["break_even_frequency_table"]
    macro("scalePrograms", len(progs))
    macro("huffLo", be["largest_package_not_helped"])
    macro("huffHi", be["smallest_package_helped"])
    macro("huffModelCorrect", be["model_correct"])
    macro("huffHelpedScaling", be["programs_helped"])
    macro("freqLo", bf["largest_package_not_helped"])
    macro("freqHi", bf["smallest_package_helped"])
    macro("freqModelCorrect", bf["model_correct"])
    full = [p for p in progs if p["huffman_symbols"] == 256]
    macro("fullAlphabet", len(full))
    if full:
        macro("fullAlphabetCanonHeader", max(p["huffman_header_bytes"] for p in full))
    lo, hi = rng([p["entropy_bits_per_byte"] for p in progs if p["clir_bytes"] > 1000], lambda x: f"{x:.2f}")
    macro("entropyMin", lo, "{}")
    macro("entropyMax", hi, "{}")
    largest = [p for p in progs if p["statements"] == s["size_classes"][-1]]
    med = lambda key: statistics.median(p[key] for p in largest)
    macro("largestRawMedian", int(med("raw_instructions")))
    macro("largestHuffGain", pct(statistics.median(reduction(p["clir_bytes"], p["huffman_bytes"]) for p in largest)), "{}")
    macro("largestFreqGain", pct(statistics.median(reduction(p["clir_bytes"], p["freq_huffman_bytes"]) for p in largest)), "{}")
    macro("largestDeflateGain", pct(statistics.median(reduction(p["clir_bytes"], p["deflate_clir"]) for p in largest)), "{}")
    macro("largestBrotliGain", pct(statistics.median(reduction(p["clir_bytes"], p["brotli_clir"]) for p in largest)), "{}")
    macro("columnarLargerScaling", sum(1 for p in progs if p["columnar_bytes"] > p["clir_bytes"]))
    import math
    xs = [math.log(p["raw_instructions"]) for p in progs]
    ys = [math.log(p["time_ms"]) for p in progs]
    mx, my = statistics.mean(xs), statistics.mean(ys)
    slope = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    macro("timeExponent", f"{slope:.2f}", "{}")
    lo, hi = rng([p["throughput_instr_per_s"] for p in progs], lambda x: f"{x:,.0f}")
    macro("throughputMin", lo, "{}")
    macro("throughputMax", hi, "{}")

    write_layout_figure(next(r for r in m if r["id"] == "S2"))

    with open(os.path.join(TABLES, "numbers.tex"), "w", encoding="utf-8") as f:
        f.write(HEADER)
        for k in sorted(macros):
            f.write(f"\\newcommand{{\\n{k}}}{{{macros[k]}}}\n")
    print(f"wrote {len(macros)} macros and the table rows to {TABLES}")


if __name__ == "__main__":
    main()
